const express = require('express');
const router = express.Router();
const {auth} = require('../middleware/authmiddleware');
const {role} = require("../middleware/roleMiddleware.js");
const { createUser ,editUser ,deleteUser, getUserData,getAllUser,getUserList} = require('../controllers/userController.js');
const {userValidation,userEditValidation} = require('../validations/userValidation.js');
const validate = require('../middleware/validationMiddleware.js');
router.route('/').post(auth,userValidation,role('admin','manager'),validate,createUser).get(auth,getAllUser);
router.route('/list').get(getUserList);
router.route('/:id').put(auth,userEditValidation,role('admin','manager'),validate,editUser).get(auth,role('admin','manager'),getUserData).delete(auth,role('admin','manager'),deleteUser);
module.exports = router;
